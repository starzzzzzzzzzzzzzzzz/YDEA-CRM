const porNome = (a: { marca: string; modelo: string }, b: { marca: string; modelo: string }) =>
  `${a.marca} ${a.modelo}`.localeCompare(`${b.marca} ${b.modelo}`, "pt-BR", { numeric: true });

/** Junta o catálogo padrão com o da empresa: o da empresa (mesmo id) vence; resultado em ordem alfabética natural. */
export function mesclarCatalogo<T extends { id: string; marca: string; modelo: string }>(padrao: T[], proprios: T[]): T[] {
  const mapa = new Map<string, T>();
  for (const p of padrao) mapa.set(p.id, p);
  for (const p of proprios) mapa.set(p.id, { ...mapa.get(p.id), ...p });
  return [...mapa.values()].sort(porNome);
}
